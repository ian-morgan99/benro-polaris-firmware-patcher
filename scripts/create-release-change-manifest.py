#!/usr/bin/env python3
"""Create the immutable change and identity record for one release candidate.

The release number is not a useful description of a build.  This record binds
the human explanation of the candidate to the exact source commits, the exact
commits since the previous candidate, and the exact firmware ZIP.  It is
generated by the canonical release script; agents must not hand-edit it after
the build.

The input summary is deliberately small and human-owned.  The source SHAs,
commit inventories, stock-package digest, ZIP digests, and appfs digest are
calculated here so they cannot be copied from an earlier candidate.

Summary format::

    {
      "baseline": {
        "candidate_id": "previous-candidate-id",
        "libgphoto2_commit": "<full SHA>",
        "patcher_commit": "<full SHA>"
      },
      "purpose": "One sentence explaining why this candidate exists",
      "changes": [
        {"component": "libgphoto2", "summary": "...", "issues": ["#123"]}
      ],
      "known_limits": ["..."],
      "validation_focus": ["..."]
    }
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
import zipfile
from datetime import datetime, timezone
from pathlib import Path


SHA_RE = re.compile(r"^[0-9a-f]{40}$")
VERSION_RE = re.compile(r"^[0-9]+(?:\.[0-9]+){4}$")
ALLOWED_COMPONENTS = {"libgphoto2", "patcher", "packaging", "tests", "docs"}


def fail(message: str) -> "NoReturn":
    raise SystemExit(f"ERROR: {message}")


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def md5_file(path: Path) -> str:
    digest = hashlib.md5()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def stock_sha256(path: Path) -> str:
    """Hash a stock ZIP or a directory deterministically."""
    if path.is_file():
        return sha256_file(path)
    if not path.is_dir():
        fail(f"stock input does not exist: {path}")
    digest = hashlib.sha256()
    for item in sorted(p for p in path.rglob("*") if p.is_file()):
        relative = item.relative_to(path).as_posix().encode()
        digest.update(len(relative).to_bytes(8, "big"))
        digest.update(relative)
        with item.open("rb") as stream:
            for chunk in iter(lambda: stream.read(1 << 20), b""):
                digest.update(chunk)
    return digest.hexdigest()


def git(repo: Path, *args: str) -> str:
    try:
        return subprocess.check_output(
            ["git", "-C", str(repo), *args], text=True, stderr=subprocess.PIPE
        ).strip()
    except subprocess.CalledProcessError as exc:
        detail = exc.stderr.strip() or "git command failed"
        fail(f"git -C {repo} {' '.join(args)}: {detail}")


def validate_sha(value: object, field: str) -> str:
    if not isinstance(value, str) or not SHA_RE.fullmatch(value):
        fail(f"{field} must be a full 40-character lower-case commit SHA")
    return value


def commit_inventory(repo: Path, baseline: str, head: str) -> list[dict[str, str]]:
    validate_sha(baseline, "baseline commit")
    validate_sha(head, "head commit")
    if git(repo, "cat-file", "-e", f"{baseline}^{{commit}}") != "":
        pass
    if git(repo, "cat-file", "-e", f"{head}^{{commit}}") != "":
        pass
    try:
        subprocess.run(
            ["git", "-C", str(repo), "merge-base", "--is-ancestor", baseline, head],
            check=True,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.PIPE,
            text=True,
        )
    except subprocess.CalledProcessError:
        fail(f"baseline {baseline} is not an ancestor of {head} in {repo}")
    raw = git(repo, "log", "--format=%H%x09%s", f"{baseline}..{head}")
    commits = []
    for line in raw.splitlines():
        sha, separator, subject = line.partition("\t")
        if not separator:
            fail(f"unexpected git log output in {repo}: {line!r}")
        commits.append({"sha": sha, "subject": subject})
    return commits


def appfs_md5(fwpkt: Path) -> str:
    firmware_info = fwpkt / "firmwareInfo"
    if not firmware_info.is_file():
        fail(f"missing firmwareInfo: {firmware_info}")
    for line in firmware_info.read_text(encoding="utf-8", errors="replace").splitlines():
        match = re.match(r"^appfs\s+size:\d+;appfs\s+MD5:([0-9a-fA-F]+);", line.strip())
        if match:
            return match.group(1).lower()
    fail("firmwareInfo has no appfs MD5 entry")


def load_summary(path: Path) -> dict:
    try:
        summary = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        fail(f"cannot read change summary {path}: {exc}")
    if not isinstance(summary, dict):
        fail("change summary root must be an object")
    baseline = summary.get("baseline")
    if not isinstance(baseline, dict):
        fail("change summary must contain a baseline object")
    if not isinstance(baseline.get("candidate_id"), str) or not baseline["candidate_id"].strip():
        fail("baseline.candidate_id must be non-empty")
    validate_sha(baseline.get("libgphoto2_commit"), "baseline.libgphoto2_commit")
    validate_sha(baseline.get("patcher_commit"), "baseline.patcher_commit")
    if not isinstance(summary.get("purpose"), str) or not summary["purpose"].strip():
        fail("purpose must be a non-empty string")
    changes = summary.get("changes")
    if not isinstance(changes, list) or not changes:
        fail("changes must be a non-empty list")
    for number, change in enumerate(changes, 1):
        if not isinstance(change, dict):
            fail(f"changes[{number}] must be an object")
        component = change.get("component")
        if component not in ALLOWED_COMPONENTS:
            fail(f"changes[{number}].component must be one of {sorted(ALLOWED_COMPONENTS)}")
        if not isinstance(change.get("summary"), str) or not change["summary"].strip():
            fail(f"changes[{number}].summary must be a non-empty string")
        issues = change.get("issues", [])
        if not isinstance(issues, list) or not all(isinstance(item, str) for item in issues):
            fail(f"changes[{number}].issues must be a list of strings")
    for field in ("known_limits", "validation_focus"):
        value = summary.get(field, [])
        if not isinstance(value, list) or not all(isinstance(item, str) and item.strip() for item in value):
            fail(f"{field} must be a list of non-empty strings")
    return summary


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--summary", type=Path, required=True)
    parser.add_argument("--candidate-id", required=True)
    parser.add_argument("--display-fwver", required=True)
    parser.add_argument("--build-id", required=True)
    parser.add_argument("--libgphoto2", type=Path, required=True)
    parser.add_argument("--patcher", type=Path, required=True)
    parser.add_argument("--stock", type=Path, required=True)
    parser.add_argument("--candidate-dir", type=Path, required=True)
    args = parser.parse_args()

    if not VERSION_RE.fullmatch(args.display_fwver):
        fail(f"display-fwver is not a five-component version: {args.display_fwver}")
    candidate_dir = args.candidate_dir.resolve()
    fwpkt = candidate_dir / "FwPkt"
    zip_path = candidate_dir / "FwPkt.zip"
    provenance = candidate_dir / "build-source-provenance.txt"
    if not fwpkt.is_dir() or not zip_path.is_file() or not provenance.is_file():
        fail("candidate must already contain FwPkt/, FwPkt.zip, and build-source-provenance.txt")

    summary = load_summary(args.summary)
    lib_head = git(args.libgphoto2, "rev-parse", "HEAD")
    patcher_head = git(args.patcher, "rev-parse", "HEAD")
    baseline = summary["baseline"]
    lib_commits = commit_inventory(args.libgphoto2, baseline["libgphoto2_commit"], lib_head)
    patcher_commits = commit_inventory(args.patcher, baseline["patcher_commit"], patcher_head)

    manifest = {
        "schema": 1,
        "generated_at_utc": datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z"),
        "candidate_id": args.candidate_id,
        "display_fwver": args.display_fwver,
        "build_id": args.build_id,
        "purpose": summary["purpose"].strip(),
        "declared_changes": summary["changes"],
        "known_limits": summary.get("known_limits", []),
        "validation_focus": summary.get("validation_focus", []),
        "baseline": baseline,
        "source": {
            "repository": "libgphoto2",
            "branch": git(args.libgphoto2, "branch", "--show-current"),
            "head_commit": lib_head,
            "commits_since_baseline": lib_commits,
        },
        "patcher": {
            "repository": "benro-polaris-firmware-patcher",
            "branch": git(args.patcher, "branch", "--show-current"),
            "head_commit": patcher_head,
            "commits_since_baseline": patcher_commits,
        },
        "artifact": {
            "stock_fwpkt_sha256": stock_sha256(args.stock.resolve()),
            "fwpkt_zip_path": str(zip_path),
            "fwpkt_zip_sha256": sha256_file(zip_path),
            "fwpkt_zip_md5": md5_file(zip_path),
            "appfs_md5": appfs_md5(fwpkt),
            "change_summary_path": str(args.summary.resolve()),
            "change_summary_sha256": sha256_file(args.summary.resolve()),
        },
        "lifecycle": {
            "built": True,
            "offline_gated": False,
            "published": False,
            "installed_verified": False,
            "physically_qualified": False,
        },
    }
    out_json = candidate_dir / "release-change-manifest.json"
    out_json.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")

    def bullet_list(items: list[str], empty: str = "(none declared)") -> list[str]:
        return [f"- {item}" for item in items] or [empty]

    lines = [
        f"# Release identity: `{args.candidate_id}`",
        "",
        "This file is generated by `scripts/build-release-candidate.sh`. It is the",
        "human-readable companion to `release-change-manifest.json`; the JSON is",
        "machine-checked and must travel with the exact published ZIP.",
        "",
        "## Immutable identity",
        "",
        f"| field | value |",
        f"|---|---|",
        f"| candidate id | `{args.candidate_id}` |",
        f"| display firmware version | `{args.display_fwver}` |",
        f"| build id | `{args.build_id}` |",
        f"| libgphoto2 commit | `{lib_head}` |",
        f"| patcher commit | `{patcher_head}` |",
        f"| stock FwPkt SHA-256 | `{manifest['artifact']['stock_fwpkt_sha256']}` |",
        f"| FwPkt ZIP SHA-256 | `{manifest['artifact']['fwpkt_zip_sha256']}` |",
        f"| FwPkt ZIP MD5 | `{manifest['artifact']['fwpkt_zip_md5']}` |",
        f"| appfs MD5 | `{manifest['artifact']['appfs_md5']}` |",
        f"| change summary SHA-256 | `{manifest['artifact']['change_summary_sha256']}` |",
        "",
        "## Why this candidate exists",
        "",
        summary["purpose"].strip(),
        "",
        "## Declared changes",
        "",
    ]
    for change in summary["changes"]:
        issues = ", ".join(change.get("issues", [])) or "no issue supplied"
        lines.append(f"- **{change['component']}** — {change['summary'].strip()} (issues: {issues})")
    lines += ["", "## Exact libgphoto2 commits since the stated baseline", ""]
    lines += [f"- `{item['sha']}` — {item['subject']}" for item in lib_commits] or ["- (no commits; the source SHA is unchanged)"]
    lines += ["", "## Exact patcher commits since the stated baseline", ""]
    lines += [f"- `{item['sha']}` — {item['subject']}" for item in patcher_commits] or ["- (no commits; the patcher SHA is unchanged)"]
    lines += [
        "",
        "## Validation focus",
        "",
        *bullet_list(summary.get("validation_focus", [])),
        "",
        "## Known limits",
        "",
        *bullet_list(summary.get("known_limits", [])),
        "",
        "## Lifecycle",
        "",
        "At generation this record is `BUILT`. Publication and deployment status",
        "is recorded separately in the PrivateResearch README, provenance file,",
        "and install receipt. `BUILT`, `GATED`, `PUBLISHED`,",
        "`INSTALLED-VERIFIED`, and `PHYSICALLY-QUALIFIED` must not be conflated.",
        "",
    ]
    (candidate_dir / "RELEASE-IDENTITY.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out_json}")
    print(f"wrote {candidate_dir / 'RELEASE-IDENTITY.md'}")
    print(f"libgphoto2 commits since baseline: {len(lib_commits)}")
    print(f"patcher commits since baseline: {len(patcher_commits)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

