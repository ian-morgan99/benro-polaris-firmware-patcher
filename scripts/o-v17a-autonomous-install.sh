#!/usr/bin/env bash
# o-v17a-autonomous-install.sh — wake Polaris via BT, stage o-v17a FwPkt to SD,
# reboot via 812, and verify the install against the immutable candidate
# manifest (issue #199 review of commit 304e899).
#
# Designed to be run by an agent session that may not have the device reachable
# yet: every phase is idempotent and re-runnable. Run with --poll to keep
# retrying the wake phase until the device answers.
#
# Phases:
#   1. WAKE    — bluetoothctl connect $BT_MAC (if /dev/hci0 exists), then wait
#                for the polaris_* AP + SSH at $GIMBAL_HOST.
#   2. AUTH    — gate destructive install on: candidate digest (zip SHA-256 ==
#                manifest), device identity (SSH host key + FwVer family), and
#                an idle/camera-state check (code 286 must not show a camera
#                in capture; ALLOW_BUSY=1 overrides).
#   3. STAGE   — stream FwPkt.zip over SSH (cat | ssh "cat > ...") to
#                /app/sd/FwPkt.zip.part, verify SHA-256 on-device, then atomic
#                rename into place (the auto-installer watches the final name).
#                Resume-aware: appends from the current .part size with a
#                prefix-hash check; bounded by STAGE_RETRY_LIMIT/WAIT.
#                Skipped when the device already reports the target FwVer
#                (no blind reflash of an already-updated device).
#   4. REBOOT  — fire protocol code 812 (SYS_REBOOT) so the on-boot FwPkt
#                watcher installs from /app/sd/. Delivery is classified:
#                observed (device went dark) or uncertain (send failed or the
#                device never went dark).
#   5. VERIFY  — wait for SSH, read /app/FwVer + provenance, then compare the
#                full SHA-256 of every mandatory installed file against the
#                immutable manifest. Verdicts: verified | installed-unverified
#                (version present but digests missing/mismatched) | not-installed.
#
# Modes:
#   (default)     wake -> auth -> stage -> reboot -> verify
#   --poll        retry wake every POLL_INTERVAL s up to POLL_LIMIT attempts;
#                 each reachable pass re-runs the full gate (stage is skipped
#                 once the target FwVer is present, so polling never blindly
#                 reflashes an already-updated device)
#   --stage-only  wake -> auth -> stage only; leave the device running (the
#                 staged-install capability without the destructive reboot)
#   --verify-only re-run phase 5 against a device that was rebooted elsewhere
#
# Env:
#   BT_MAC        (default 48:E7:DA:D4:B5:72)
#   GIMBAL_HOST   (default 192.168.0.1)
#   GIMBAL_PORT   (default 9090, wire protocol port for 812/286)
#   GIMBAL_SSH    (default root@<GIMBAL_HOST>)
#   FWPKT_ZIP     (default out/staged/o-v17a-shutter-fallback-off-20261012/FwPkt.zip)
#   MANIFEST      (default <FWPKT_ZIP dir>/install-manifest.json; generated by
#                 scripts/generate-fwpkt-manifest.py — immutable per candidate)
#   EXPECTED_MD5  (auto-computed from FWPKT_ZIP if unset; kept for compatibility)
#   MAX_WAIT      (default 900 s for the device to come back after reboot)
#   WAKE_WAIT     (default 120 s between wake attempts)
#   REBOOT_DARK_WATCH (default 60 s to wait for device to go dark)
#   SETTLE_WAIT   (default 30 s to let polestar_app settle + getFwInfo run)
#   POLL_INTERVAL (default 30 s between wake attempts in --poll mode)
#   POLL_LIMIT    (default 120 attempts in --poll mode)
#   ALLOW_BUSY    (default 0; set 1 to override the camera-busy gate)
#   EXPECTED_HOST_KEY  (optional; the device's recorded public key. When set,
#                 the scanned host key must match exactly — no implicit trust.)
#   KNOWN_HOSTS   (optional; file used with StrictHostKeyChecking=accept-new;
#                 first contact pins the key, later contacts must match)
#
# Exit codes:
#   0 verified install (or --stage-only staged OK / --verify-only verified)
#   1 manifest/input error
#   2 poll exhausted
#   3 device not reachable
#   4 stage failed
#   5 verify failed (installed-unverified or not-installed)
#   6 auth gate failed (digest/identity/busy)

set -uo pipefail

cd "$(dirname "$0")/.." || exit 1

BT_MAC="${BT_MAC:-48:E7:DA:D4:B5:72}"
GIMBAL_HOST="${GIMBAL_HOST:-192.168.0.1}"
GIMBAL_PORT="${GIMBAL_PORT:-9090}"
GIMBAL_SSH="${GIMBAL_SSH:-root@${GIMBAL_HOST}}"
FWPKT_ZIP="${FWPKT_ZIP:-out/staged/o-v17a-shutter-fallback-off-20261012/FwPkt.zip}"
MANIFEST="${MANIFEST:-$(dirname "$FWPKT_ZIP")/install-manifest.json}"
MAX_WAIT="${MAX_WAIT:-900}"
WAKE_WAIT="${WAKE_WAIT:-120}"
REBOOT_DARK_WATCH="${REBOOT_DARK_WATCH:-60}"
SETTLE_WAIT="${SETTLE_WAIT:-30}"
POLL_INTERVAL="${POLL_INTERVAL:-30}"
POLL_LIMIT="${POLL_LIMIT:-120}"
ALLOW_BUSY="${ALLOW_BUSY:-0}"
WIRE_REBOOT='1&812&0&#'
WIRE_CAMSTATE='1&286&0&#'

[ -f "$FWPKT_ZIP" ] || { echo "ERROR: FWPKT_ZIP not found: $FWPKT_ZIP"; exit 1; }
EXPECTED_MD5="${EXPECTED_MD5:-$(md5sum "$FWPKT_ZIP" | cut -d' ' -f1)}"
ZIP_SHA256="$(sha256sum "$FWPKT_ZIP" | cut -d' ' -f1)"

log() { echo "[o-v17a-install $(date +%H:%M:%S)] $*"; }

# --- SSH with host-identity verification (review finding 2) ------------------
# Default: accept-new against a per-host known_hosts file (first contact is
# pinned, later contacts must match). With EXPECTED_HOST_KEY set: the device's
# key must equal the recorded key exactly — no implicit trust.
KNOWN_HOSTS="${KNOWN_HOSTS:-$HOME/.ssh/polaris-${GIMBAL_HOST}.known_hosts}"
if [ -n "${EXPECTED_HOST_KEY:-}" ]; then
  SSH_OPTS="-o ConnectTimeout=5 -o BatchMode=yes -o StrictHostKeyChecking=no"
else
  touch "$KNOWN_HOSTS" 2>/dev/null || KNOWN_HOSTS="$(mktemp)"
  SSH_OPTS="-o ConnectTimeout=5 -o BatchMode=yes -o StrictHostKeyChecking=accept-new -o UserKnownHostsFile=$KNOWN_HOSTS"
fi

ssh_dev() { ssh $SSH_OPTS "$GIMBAL_SSH" "$@" 2>/dev/null; }

check_host_key() {
  [ -n "${EXPECTED_HOST_KEY:-}" ] || return 0
  local actual
  actual="$(ssh-keyscan -T 5 "$GIMBAL_HOST" 2>/dev/null | awk '{print $1" "$3}' | head -1)"
  if [ -z "$actual" ]; then
    log "AUTH: host key scan failed (device not reachable on SSH port?)"
    return 1
  fi
  local expected="${EXPECTED_HOST_KEY#* }"   # strip optional 'ssh-ed25519' prefix
  case "$actual" in
    *"$expected"*) log "AUTH: host key matches recorded identity"; return 0 ;;
    *) log "AUTH: host key MISMATCH (got: ${actual%% *}…) — refusing destructive install"; return 1 ;;
  esac
}

tcp_open() { (exec 3<>"/dev/tcp/${GIMBAL_HOST}/${GIMBAL_PORT}") 2>/dev/null && { exec 3>&-; return 0; } || return 1; }

# --- Bluetooth reachability --------------------------------------------------
# Two faults used to hide behind a single silent fallback here:
#   * `[ -e /dev/hci0 ]` is false inside the VS Code Flatpak even though the
#     host has an adapter; the portal reaches it (flatpak-spawn --host).
#   * `bluetoothctl connect` prints "Attempting to connect ..." and exits 0
#     before BlueZ resolves anything, so "BT connect returned OK" was never
#     evidence of a delivered pulse (OpenPolaris #97 documents this exact shape
#     in the Kotlin path).
# Both are handled by scripts/polaris-bt-probe.sh; wake is now claimed only on a
# link that is verifiably held.
BT_PROBE_LIB="$(cd "$(dirname "$0")" && pwd)/polaris-bt-probe.sh"
if [ -r "$BT_PROBE_LIB" ]; then
  # shellcheck source=./polaris-bt-probe.sh
  . "$BT_PROBE_LIB"
else
  BT_ROUTE="none"; BT_CMD=()
  bt_resolve() { return 2; }
  bt_timeout() { return 127; }
  bt_exec() { return 127; }
  bt_wake_pulse() { return 2; }
  bt_radio_liveness() { BT_LIVENESS_DETAIL="probe module missing"; return 3; }
fi
bt_resolve || true

phase_wake() {
  case "$BT_ROUTE" in
    local|portal)
      log "WAKE: sending BT pulse to $BT_MAC (route=$BT_ROUTE)"
      # Success means the GATT link is established AND still held 2 s later.
      if bt_wake_pulse "$BT_MAC"; then
        log "WAKE: GATT link established and held"
      else
        log "WAKE: no held link (bluetoothctl may still exit 0 — see OpenPolaris #97); continuing to probe anyway"
      fi
      ;;
    *)
      # Loud, not silent. Previously this logged "relying on AP/SSH already up"
      # and the run proceeded as if a pulse had been sent.
      log "WAKE: NO BLUETOOTH PATH from this host (route=${BT_ROUTE:-none}; flatpak=$([ -r /.flatpak-info ] && echo yes || echo no)). No wake pulse was sent. Only an already-awake device will be reached — if the rig is asleep this is a HOST limitation, not a firmware fault."
      ;;
  esac
  local i
  for i in $(seq 1 $((WAKE_WAIT / 5))); do   # WAKE_WAIT s of 5 s probes
    if tcp_open && ssh_dev "true"; then
      log "WAKE: device reachable (TCP $GIMBAL_PORT + SSH)"
      return 0
    fi
    sleep 5
  done
  return 1
}

# --- Auth gate (review finding 2): digest + device identity + idle check ------
manifest_zip_sha() { python3 -c 'import json,sys;print(json.load(open(sys.argv[1]))["zip"]["sha256"])' "$MANIFEST" 2>/dev/null; }
manifest_fwver()   { python3 -c 'import json,sys;print(json.load(open(sys.argv[1]))["fwver_content"])' "$MANIFEST" 2>/dev/null; }

# --- Wire send with /dev/tcp fallback ----------------------------------------
# `nc` is NOT installed on every host (e.g. this workstation: `which nc` empty),
# in which case the old `timeout 10 nc ...` always exited 127 and the 812 frame
# was never actually delivered — the script then (correctly) reported
# "delivery uncertain" on every attempt. Prefer nc when present; otherwise use
# bash's /dev/tcp: open a bidirectional socket, write the frame, close the
# write side (EOF to the device), read any reply for ~1s, close.
# rc: 0 = frame written (reply printed, may be empty). A timeout (124) also means
# the frame was delivered — the device simply kept the socket open — so it is
# normalised to success. Non-zero otherwise (connect/write failed).
wire_send() { # $1 = wire frame; prints the device reply (may be empty)
  local frame="$1" rc
  if command -v nc >/dev/null 2>&1; then
    printf '%s' "$frame" | timeout 8 nc "$GIMBAL_HOST" "$GIMBAL_PORT" 2>/dev/null
    rc=$?
  else
    timeout 8 bash -c '
      exec 3<>/dev/tcp/"$1"/"$2" || exit 1
      printf "%s" "$3" >&3 || exit 1
      exec 4<&3          # keep a read-side copy of the socket
      exec 3>&-          # close the write side -> device sees EOF, may still reply
      sleep 1            # allow the reply to arrive
      cat <&4 2>/dev/null
    ' _ "$GIMBAL_HOST" "$GIMBAL_PORT" "$frame"
    rc=$?
  fi
  [ "$rc" -eq 0 ] || [ "$rc" -eq 124 ]
}

phase_auth() {
  log "AUTH: gating destructive install (digest + identity + idle)"
  [ -f "$MANIFEST" ] || { log "AUTH: manifest not found: $MANIFEST (run scripts/generate-fwpkt-manifest.py)"; return 1; }
  local mzip
  mzip="$(manifest_zip_sha)"
  if [ -z "$mzip" ]; then
    log "AUTH: manifest unreadable/invalid: $MANIFEST"; return 1
  fi
  if [ "$mzip" != "$ZIP_SHA256" ]; then
    log "AUTH: candidate digest mismatch (zip=$ZIP_SHA256 manifest=$mzip) — refusing"; return 1
  fi
  log "AUTH: candidate digest matches manifest ($ZIP_SHA256)"
  check_host_key || return 1
  # Device identity: the running FwVer must be a 6.0.0.54.x family string we can
  # reason about (a foreign/blank version means we are not talking to the Polaris).
  local cur
  cur="$(ssh_dev "cat /app/FwVer 2>/dev/null")"
  case "$cur" in
    *6.0.0.54.*) log "AUTH: device identity OK (current FwVer: $cur)";;
    *) log "AUTH: unexpected device FwVer '${cur:-<unreadable>}' — refusing destructive install"; return 1;;
  esac
  # Idle/camera-state check: query code 286. A camera in capture (state:1 with a
  # live session) must not be rebooted mid-exposure unless explicitly allowed.
  local cam
  cam="$(wire_send "$WIRE_CAMSTATE" | tr -d '\r')"
  log "AUTH: camera-state reply: ${cam:-<none>}"
  case "$cam" in
    *state:1*)
      if [ "$ALLOW_BUSY" = "1" ]; then
        log "AUTH: camera present (state:1) — proceeding because ALLOW_BUSY=1"
      else
        log "AUTH: camera busy/present (state:1) — refusing reboot; re-run with ALLOW_BUSY=1 to override"; return 1
      fi ;;
    *state:-5*|*state:-1*) log "AUTH: camera absent/failed (idle) — OK" ;;
    "") log "AUTH: no 286 reply (camera queries unanswered = idle) — OK" ;;
    *)
      # The device can answer the 286 query with an unrelated frame (e.g. its
      # continuous 284 gimbal-telemetry stream sitting on the socket), which is
      # neither a busy nor a recognised idle reply. Honour the documented
      # ALLOW_BUSY escape hatch here too — the message always promised it, but
      # only the state:1 branch implemented it. Confirm idle out-of-band
      # (a bare 1&286&0&# that returns nothing) before setting ALLOW_BUSY=1.
      if [ "$ALLOW_BUSY" = "1" ]; then
        log "AUTH: unrecognised camera-state reply — proceeding because ALLOW_BUSY=1"
      else
        log "AUTH: unrecognised camera-state reply — refusing (ALLOW_BUSY=1 to override)"; return 1
      fi ;;
  esac
  return 0
}

# --- Stage with no-blind-reflash (review finding 3) --------------------------
device_fwver() { ssh_dev "cat /app/FwVer 2>/dev/null"; }

phase_stage() {
  local target cur
  target="$(manifest_fwver)"
  cur="$(device_fwver)"
  if [ -n "$target" ] && [ "$cur" = "$target" ]; then
    log "STAGE: device already reports target FwVer ($cur) — skipping reflash (no blind re-stage)"
    return 0
  fi
  # Transfer strategy (field-validated 2026-10-16):
  #  - cat-over-ssh: the Polaris' OpenSSH rejects the SFTP subsystem
  #    ("scp: Connection closed") and legacy scp -O hangs, so the zip is
  #    streamed with `cat | ssh "cat > ..."`.
  #  - .part + atomic rename: written to /app/sd/FwPkt.zip.part FIRST,
  #    verified by SHA-256, then renamed into place. The firmware's
  #    auto-installer watches /app/sd/FwPkt.zip and reboots the device when
  #    it sees a complete zip — writing directly there mid-transfer triggered
  #    an uncontrolled reboot (observed: device went dark at ~29 MB of 68 MB).
  #  - resume-aware: the AP link flaps (device stays up; uptime keeps
  #    climbing across dark periods), so each attempt appends from the
  #    current on-device size. Before every resume the on-device prefix is
  #    verified against the local zip (head -c N | sha256sum both sides); a
  #    mismatch or an over-appended size (> total) forces a fresh write.
  #    Stray transfer pipes from earlier interrupted runs are killed at stage
  #    start so two writers can never append concurrently. Bounded by
  #    STAGE_RETRY_LIMIT / STAGE_RETRY_WAIT.
  local total off attempt=0
  total="$(stat -c %s "$FWPKT_ZIP" 2>/dev/null || wc -c < "$FWPKT_ZIP")"
  log "STAGE: pushing FwPkt.zip (${total} bytes) -> /app/sd/FwPkt.zip.part (resume-aware)"
  # Kill stray transfer pipes from earlier (killed/interrupted) runs of this
  # script: a zombie 'cat | ssh' still appending to .part concurrently
  # corrupts the resume (observed 2026-10-16: .part over-appended to 122 MB).
  pkill -f "cat >> /app/sd/FwPkt.zip.part" 2>/dev/null || true
  pkill -f "cat > /app/sd/FwPkt.zip.part" 2>/dev/null || true
  while :; do
    attempt=$((attempt+1))
    if ! ssh_dev "true"; then
      log "STAGE: attempt $attempt — device unreachable, waiting ${STAGE_RETRY_WAIT}s for the link"
      sleep "$STAGE_RETRY_WAIT"
      [ "$attempt" -ge "${STAGE_RETRY_LIMIT:-8}" ] && { log "STAGE: retry limit reached"; return 1; }
      continue
    fi
    off="$(ssh_dev "stat -c %s /app/sd/FwPkt.zip.part 2>/dev/null || echo 0" | tr -d '[:space:]')"
    case "$off" in (*[!0-9]*|"") off=0 ;; esac
    if [ "$off" -gt "$total" ]; then
      log "STAGE: .part over-appended (${off} > ${total}) — starting fresh"
      ssh_dev "rm -f /app/sd/FwPkt.zip.part" >/dev/null 2>&1
      off=0
    elif [ "$off" -eq "$total" ]; then
      log "STAGE: .part already complete on device (${off} bytes) — verifying"
      break
    fi
    if [ "$off" -gt 0 ]; then
      # Verify the on-device prefix actually matches the local zip before
      # appending — a stale/corrupt .part must never be resumed blindly.
      local lpfx dpfx
      lpfx="$(head -c "$off" "$FWPKT_ZIP" | sha256sum | cut -d' ' -f1)"
      dpfx="$(ssh_dev "head -c $off /app/sd/FwPkt.zip.part 2>/dev/null | sha256sum | cut -d' ' -f1")"
      if [ -n "$dpfx" ] && [ "$lpfx" = "$dpfx" ]; then
        log "STAGE: attempt $attempt — prefix verified (${off} bytes) — resuming"
        tail -c +"$((off+1))" "$FWPKT_ZIP" | ssh $SSH_OPTS "$GIMBAL_SSH" "cat >> /app/sd/FwPkt.zip.part" >/dev/null 2>&1
      else
        log "STAGE: attempt $attempt — prefix mismatch (device=${dpfx:-<unreadable>}) — fresh transfer"
        cat "$FWPKT_ZIP" | ssh $SSH_OPTS "$GIMBAL_SSH" "cat > /app/sd/FwPkt.zip.part" >/dev/null 2>&1
      fi
    else
      log "STAGE: attempt $attempt — fresh transfer (0/${total} bytes)"
      cat "$FWPKT_ZIP" | ssh $SSH_OPTS "$GIMBAL_SSH" "cat > /app/sd/FwPkt.zip.part" >/dev/null 2>&1
    fi
    # Re-read the size: == total → done; > total → over-appended (corrupt);
    # advanced but short → link dropped, resume next attempt; unchanged → lost.
    local now
    now="$(ssh_dev "stat -c %s /app/sd/FwPkt.zip.part 2>/dev/null || echo 0" | tr -d '[:space:]')"
    case "$now" in (*[!0-9]*|"") now=0 ;; esac
    if [ "$now" -eq "$total" ]; then
      log "STAGE: transfer complete (${now} bytes)"
      break
    fi
    if [ "$now" -gt "$total" ]; then
      log "STAGE: over-appended to ${now} — will start fresh next attempt"
      ssh_dev "rm -f /app/sd/FwPkt.zip.part" >/dev/null 2>&1
    elif [ "$now" -gt "$off" ]; then
      log "STAGE: link dropped at ${now}/${total} — will resume next attempt"
    else
      log "STAGE: no progress this attempt (still ${now}/${total}) — retrying fresh"
      ssh_dev "rm -f /app/sd/FwPkt.zip.part" >/dev/null 2>&1
    fi
    [ "$attempt" -ge "${STAGE_RETRY_LIMIT:-8}" ] && { log "STAGE: retry limit reached at ${now}/${total}"; return 1; }
    sleep "${STAGE_RETRY_WAIT:-60}"
  done
  local actual
  actual="$(ssh_dev "sha256sum /app/sd/FwPkt.zip.part 2>/dev/null | cut -d' ' -f1")"
  if [ "$actual" = "$ZIP_SHA256" ]; then
    ssh_dev "mv -f /app/sd/FwPkt.zip.part /app/sd/FwPkt.zip" >/dev/null 2>&1 \
      || { log "STAGE: rename .part -> FwPkt.zip failed"; return 1; }
    log "STAGE: on-device sha256 matches ($ZIP_SHA256) — staged atomically"
    return 0
  fi
  ssh_dev "rm -f /app/sd/FwPkt.zip.part" >/dev/null 2>&1
  log "STAGE: sha256 mismatch (device=${actual:-<unreadable>} expected=$ZIP_SHA256)"
  return 1
}

# --- Reboot with delivery classification (review finding 3) ------------------
# Returns: 0 = observed reboot, 1 = uncertain delivery.
phase_reboot() {
  local up_before
  up_before="$(ssh_dev "awk '{print int(\$1)}' /proc/uptime 2>/dev/null")"
  log "REBOOT: firing 812 (SYS_REBOOT); uptime before=${up_before:-<unknown>}s"
  if wire_send "$WIRE_REBOOT" >/dev/null; then
    log "REBOOT: 812 send OK — watching for the device to go dark"
  else
    log "REBOOT: 812 send FAILED (delivery uncertain)"
  fi
  # Observed reboot = SSH goes dark within REBOOT_DARK_WATCH s. If it never does,
  # the command may not have been delivered; report uncertain and let the caller
  # decide (verify can still prove the version without claiming a reboot).
  local i
  for i in $(seq 1 $((REBOOT_DARK_WATCH / 5))); do
    if ! ssh_dev "true"; then
      log "REBOOT: device went dark at ~$((i*5))s — reboot observed"
      return 0
    fi
    sleep 5
  done
  log "REBOOT: device still up after ${REBOOT_DARK_WATCH}s — delivery UNCERTAIN (not claiming a successful reboot)"
  return 1
}

# --- Verify against the immutable manifest (review finding 1) -----------------
phase_verify() {
  log "VERIFY: waiting up to ${MAX_WAIT}s for the device to come back"
  local i
  for i in $(seq 1 $((MAX_WAIT / 15))); do
    if ssh_dev "true"; then break; fi
    sleep 15
  done
  ssh_dev "true" || { log "VERIFY: SSH still down after ${MAX_WAIT}s — verdict: not-installed (unreachable)"; return 1; }
  sleep "$SETTLE_WAIT"   # let polestar_app settle + getFwInfo run
  local fwver target
  fwver="$(ssh_dev "cat /app/FwVer 2>/dev/null")"
  target="$(manifest_fwver)"
  log "VERIFY: /app/FwVer = ${fwver:-<unreadable>} (target: ${target:-<unknown>})"
  if [ -n "$target" ] && [ "$fwver" != "$target" ]; then
    log "VERIFY: FwVer does not match target — verdict: not-installed"
    return 1
  fi
  # Version string is necessary but NOT sufficient (review finding 1): compare
  # every mandatory installed file's full SHA-256 against the manifest.
  local stage2_mandatory
  stage2_mandatory="$(python3 -c 'import json,sys;print(str(json.load(open(sys.argv[1])).get("stage2_mandatory",True)).lower())' "$MANIFEST" 2>/dev/null)"
  local failures=0
  while IFS='|' read -r devpath expected_sha; do
    [ -n "$devpath" ] || continue
    # stage2 files are mandatory only when the candidate ships a lib/stage2 tree
    if [[ "$devpath" == /app/lib/stage2/* ]] && [ "$stage2_mandatory" = "false" ]; then
      continue
    fi
    local actual
    actual="$(ssh_dev "sha256sum $devpath 2>/dev/null | cut -d' ' -f1")"
    if [ -z "$actual" ]; then
      log "VERIFY: MISSING/UNREADABLE $devpath (expected sha256 ${expected_sha:0:12}…)"
      failures=$((failures+1))
    elif [ "$actual" != "$expected_sha" ]; then
      log "VERIFY: MISMATCH $devpath (device=${actual:0:12}… expected=${expected_sha:0:12}…)"
      failures=$((failures+1))
    else
      log "VERIFY: OK $devpath (${actual:0:12}…)"
    fi
  done < <(python3 - "$MANIFEST" <<'PYEOF'
import json, sys
m = json.load(open(sys.argv[1]))
for f in m["files"]:
    print(f['path'] + "|" + f['sha256'])
PYEOF
)

  local provenance
  provenance="$(ssh_dev "sed -n 's/^build_id=//p' /app/openpolaris-libgphoto2-provenance.txt 2>/dev/null | head -1")"
  [ -n "$provenance" ] && log "VERIFY: on-device build_id: $provenance"

  if [ "$failures" -eq 0 ]; then
    log "VERDICT: verified — FwVer ${fwver} + all mandatory installed files match the immutable manifest"
    return 0
  fi
  log "VERDICT: installed-unverified — FwVer present but $failures mandatory file digest(s) missing/mismatched"
  return 1
}

run_full() {
  phase_auth || return 6
  phase_stage || return 4
  if [ "${MODE}" = "--stage-only" ]; then
    log "DONE: staged (device left running; reboot not fired)"
    return 0
  fi
  local rc=0
  phase_reboot || rc=7
  if phase_verify; then
    if [ "$rc" -eq 7 ]; then
      log "DONE: install verified, but reboot delivery was uncertain (device never went dark)"
    else
      log "DONE: full autonomous install complete (reboot observed + verified)"
    fi
    return 0
  fi
  return 5
}

case "${1:-}" in
  --poll)
    MODE="--poll"
    log "POLL mode: retrying wake every ${POLL_INTERVAL}s up to ${POLL_LIMIT} attempts"
    n=0
    while [ $n -lt "$POLL_LIMIT" ]; do
      n=$((n+1))
      if phase_wake; then
        run_full && { log "DONE: full autonomous install complete"; exit 0; }
        # Device went dark after reboot, or a gate failed — re-wake and continue.
        # (stage is skipped once the target FwVer is present, so polling never
        # blindly reflashes an already-updated device.)
        sleep "$POLL_INTERVAL"
      else
        sleep "$POLL_INTERVAL"
      fi
    done
    log "POLL mode: exhausted ${POLL_LIMIT} attempts"
    exit 2
    ;;
  --stage-only)
    MODE="--stage-only"
    phase_wake || { log "device not reachable — re-run with --poll or wake manually"; exit 3; }
    run_full || exit $?
    ;;
  --verify-only)
    MODE="--verify-only"
    [ -f "$MANIFEST" ] || { echo "ERROR: manifest not found: $MANIFEST"; exit 1; }
    phase_verify || exit 5
    log "DONE: verify-only complete"
    ;;
  *)
    MODE=""
    phase_wake   || { log "device not reachable — re-run with --poll or wake manually"; exit 3; }
    run_full || exit $?
    ;;
esac
