#!/usr/bin/env bash
# release-fwpkt.sh — THE supported install path: stage → verify → reboot → confirm.
#
# This is the only installer that stages the extracted FwPkt/ TREE, which is what
# the on-boot watcher actually consumes. Staging only FwPkt.zip is silently ignored
# (issue #58) and has repeatedly produced "install succeeded" reports against a
# device that never changed. The two older scripts
# (scripts/attempt-fwpkt-install.sh, scripts/o-v17a-autonomous-install.sh) stage the
# zip only and are deprecated in favour of this one; see
# docs/FIRMWARE-INSTALL-PROCESS.md for the full rationale.
#
# Usage:
#   ./scripts/release/release-fwpkt.sh <build-dir> [options]
#
# Options:
#   --host IP          Polaris IP (default 192.168.0.1)
#   --ssh-user USER    SSH user (default root)
#   --skip-trigger     stage + verify only, do not reboot
#   --skip-verify      skip the post-reboot verification (fire-and-forget)
#   --max-wait SECS    max seconds to wait for device to return (default 900)
#   --allow-busy       proceed even if a camera is present/busy (code 286 state:1)
#
# What it does:
#   0. Gate: candidate zip digest vs install-manifest.json, device identity
#      (FwVer family), and an idle/camera check — refuse a destructive flash
#      unless all three pass.
#   1. Pre-flight: SSH reachable, /app/sd has space
#   2. Stage: stream the extracted FwPkt/ tree to /app/sd/FwPkt/, then remove any
#      stray FwPkt.zip/.part so the watcher cannot pick up a stale package
#   3. Verify: recompute MD5s on-device, compare to firmwareInfo (fail closed)
#   4. Trigger: sync + /sbin/reboot (on-boot watcher fires SP_UpgradeCheckFw)
#   5. Wait: poll SSH until the device returns (5-10 min for NAND reflash), and
#      require /proc/uptime to have RESET — an AP-link flap is not a reboot
#   6. Confirm: fail-closed exact comparison of build_id, both source commits,
#      display version and every mandatory installed file's SHA-256
set -euo pipefail

BUILD_DIR=""
HOST="192.168.0.1"
SSH_USER="root"
SKIP_TRIGGER=0
SKIP_VERIFY=0
MAX_WAIT=900
ALLOW_BUSY=0
GIMBAL_PORT=9090

while [ $# -gt 0 ]; do
  case "$1" in
    --host) HOST="$2"; shift 2;;
    --ssh-user) SSH_USER="$2"; shift 2;;
    --skip-trigger) SKIP_TRIGGER=1; shift;;
    --skip-verify) SKIP_VERIFY=1; shift;;
    --max-wait) MAX_WAIT="$2"; shift 2;;
    --allow-busy) ALLOW_BUSY=1; shift;;
    -h|--help) sed -n '2,32p' "$0"; exit 0;;
    *) BUILD_DIR="$1"; shift;;
  esac
done

[ -n "$BUILD_DIR" ] || { echo "usage: $0 <build-dir> [options]" >&2; exit 2; }
BUILD_DIR="$(cd "$BUILD_DIR" && pwd)"
SSH="${SSH_USER}@${HOST}"
FWPKT_DIR="$BUILD_DIR/FwPkt"

[ -d "$FWPKT_DIR" ] || { echo "ERROR: $FWPKT_DIR not found" >&2; exit 2; }
[ -f "$FWPKT_DIR/firmwareInfo" ] || { echo "ERROR: firmwareInfo missing" >&2; exit 2; }
[ -f "$FWPKT_DIR/FwVer" ] || { echo "ERROR: candidate FwVer missing" >&2; exit 2; }

# Read the expected build_id from provenance (if present)
EXPECTED_BUILD_ID=""
if [ -f "$BUILD_DIR/build-source-provenance.txt" ]; then
  EXPECTED_BUILD_ID="$(sed -n 's/^build_id=//p' "$BUILD_DIR/build-source-provenance.txt")"
fi

# The candidate zip digest must match the immutable manifest. A build dir whose
# zip has been edited, truncated or swapped since the gate ran must never be
# flashed, so this is checked before anything touches the device.
EXPECTED_ZIP_SHA256=""
if [ -f "$BUILD_DIR/install-manifest.json" ]; then
  EXPECTED_ZIP_SHA256="$(python3 -c 'import json,sys;print(json.load(open(sys.argv[1]))["zip"]["sha256"])' \
    "$BUILD_DIR/install-manifest.json" 2>/dev/null || true)"
fi
if [ -z "$EXPECTED_ZIP_SHA256" ]; then
  echo "ERROR: install-manifest.json missing or unreadable in $BUILD_DIR" >&2
  echo "       Every candidate must carry one (generated by the release build)." >&2
  exit 2
fi
ACTUAL_ZIP_SHA256="$(sha256sum "$BUILD_DIR/FwPkt.zip" | cut -d' ' -f1)"
if [ "$ACTUAL_ZIP_SHA256" != "$EXPECTED_ZIP_SHA256" ]; then
  echo "ERROR: candidate zip digest mismatch" >&2
  echo "       actual   = $ACTUAL_ZIP_SHA256" >&2
  echo "       manifest = $EXPECTED_ZIP_SHA256" >&2
  exit 2
fi

echo "=== release-fwpkt.sh $(date -u +%FT%TZ) ==="
echo "Build dir:   $BUILD_DIR"
echo "Target:      $SSH"
echo "Build ID:    ${EXPECTED_BUILD_ID:-<none>}"
echo "Zip SHA-256: $ACTUAL_ZIP_SHA256"
echo

# --- 1. Pre-flight -----------------------------------------------------------
echo "--- [1/6] Pre-flight ---"
if ! timeout 5 ssh -o BatchMode=yes -o ConnectTimeout=5 "$SSH" 'true' 2>/dev/null; then
  echo "ERROR: SSH to $SSH failed." >&2; exit 3
fi
echo "SSH: OK"

SD_FREE_KB="$(ssh -o BatchMode=yes "$SSH" 'df -k /app/sd 2>/dev/null | tail -1' | awk '{print $4}')"
echo "/app/sd free: ${SD_FREE_KB:-unknown} KB"
if [ -n "$SD_FREE_KB" ] && [ "$SD_FREE_KB" -lt 100000 ]; then
  echo "WARN: low space on /app/sd (${SD_FREE_KB} KB)" >&2
fi

# Device identity: the running FwVer must be a recognisable 6.0.0.54.x string.
# A blank or foreign version means we are not talking to the Polaris and must
# not be reflashed.
CUR_FWVER="$(ssh -o BatchMode=yes "$SSH" 'cat /app/FwVer 2>/dev/null' || true)"
case "$CUR_FWVER" in
  *6.0.0.54.*) echo "Device identity: OK (running $CUR_FWVER)";;
  *) echo "ERROR: unexpected device FwVer '${CUR_FWVER:-<unreadable>}' — refusing destructive flash" >&2; exit 3;;
esac

# No blind reflash: if the device already runs the target version, staging again
# is pointless and a reboot is pure risk.
TARGET_FWVER="$(cat "$FWPKT_DIR/FwVer" 2>/dev/null | tr -d '\r\n')"
if [ -n "$TARGET_FWVER" ] && [ "$CUR_FWVER" = "$TARGET_FWVER" ]; then
  echo "Device already reports target FwVer ($CUR_FWVER) — nothing to do."
  exit 0
fi
echo "Target FwVer: $TARGET_FWVER (current $CUR_FWVER)"

# Idle/camera check (protocol code 286). Rebooting while a camera is mid-capture
# abandons an exposure and leaves the output unrecoverable, so refuse unless
# --allow-busy is given. A missing reply means nothing is answering, i.e. idle.
wire_send() { # $1 = wire frame; prints the device reply (may be empty)
  local frame="$1" rc
  if command -v nc >/dev/null 2>&1; then
    printf '%s' "$frame" | timeout 8 nc "$HOST" "$GIMBAL_PORT" 2>/dev/null
    rc=$?
  else
    timeout 8 bash -c '
      exec 3<>/dev/tcp/"$1"/"$2" || exit 1
      printf "%s" "$3" >&3 || exit 1
      exec 4<&3; exec 3>&-; sleep 1; cat <&4 2>/dev/null
    ' _ "$HOST" "$GIMBAL_PORT" "$frame"
    rc=$?
  fi
  # A timeout (124) means the frame was delivered and the device simply kept the
  # socket open, which is normal here.
  [ "$rc" -eq 0 ] || [ "$rc" -eq 124 ]
}
CAMSTATE="$(wire_send '1&286&0&#' | tr -d '\r')"
echo "Camera state (286): ${CAMSTATE:-<none>}"
case "$CAMSTATE" in
  *state:1*)
    if [ "$ALLOW_BUSY" = "1" ]; then
      echo "  WARN: camera present (state:1) — proceeding because --allow-busy"
    else
      echo "ERROR: camera present/busy (state:1) — refusing to reboot mid-exposure." >&2
      echo "       Re-run with --allow-busy only after confirming no exposure is in flight." >&2
      exit 3
    fi ;;
  *state:-5*|*state:-1*|"") echo "  Idle (camera absent or unanswered) — OK" ;;
  *)
    # The device can answer with an unrelated frame (e.g. its continuous 284
    # gimbal telemetry already sitting on the socket). Treat that as unknown and
    # refuse rather than guess, honouring --allow-busy as the documented override.
    if [ "$ALLOW_BUSY" = "1" ]; then
      echo "  WARN: unrecognised camera-state reply — proceeding because --allow-busy"
    else
      echo "ERROR: unrecognised camera-state reply '${CAMSTATE}' — refusing (--allow-busy to override)" >&2
      exit 3
    fi ;;
esac

# --- 2. Stage ----------------------------------------------------------------
echo "--- [2/6] Staging FwPkt/ tree to /app/sd/FwPkt/ ---"
# Remove any existing partial tree first (clean slate)
ssh -o BatchMode=yes "$SSH" 'rm -rf /app/sd/FwPkt 2>/dev/null; true'

# Stream the tree
echo "Streaming $(du -sh "$FWPKT_DIR" | cut -f1) to device..."
tar czf - -C "$BUILD_DIR" FwPkt | \
  ssh -o BatchMode=yes -o ServerAliveInterval=10 "$SSH" 'tar xzf - -C /app/sd && sync'
echo "Staged. Verifying on-device layout..."
ssh -o BatchMode=yes "$SSH" 'ls /app/sd/FwPkt/ && echo OK'

# Remove any stray zip/partial transfer left by an earlier attempt. The watcher
# consumes the tree, but a stale FwPkt.zip beside it has caused ambiguous runs and
# in one case an uncontrolled reboot mid-transfer.
ssh -o BatchMode=yes "$SSH" 'rm -f /app/sd/FwPkt.zip /app/sd/FwPkt.zip.part 2>/dev/null; true'
echo "Stray FwPkt.zip/.part cleared."

# --- 3. Verify MD5s ----------------------------------------------------------
# NOTE: the device runs busybox sh (no bash). The script below is POSIX-only.
echo "--- [3/6] Verifying firmwareInfo MD5s on-device ---"
ssh -o BatchMode=yes "$SSH" 'sh -s' << 'VERIFY_EOF'
set -e
cd /app/sd/FwPkt
FAIL=0
while IFS= read -r line; do
  # Parse: "KEY size:N;KEY MD5:hash;"
  key=$(echo "$line" | sed -n "s/^\([a-zA-Z0-9]*\) size:.*/\1/p")
  [ -z "$key" ] && continue
  expected_md5=$(echo "$line" | sed -n "s/.*${key} MD5:\\([0-9a-fA-F][0-9a-fA-F]*\\);.*/\\1/p")
  # Find the file: camera/KEY[.ubifs] or gimbal/KEY_*.bin
  file=""
  if [ -f "camera/$key" ]; then file="camera/$key"
  elif [ -f "camera/${key}.ubifs" ]; then file="camera/${key}.ubifs"
  elif [ -f "gimbal/${key}_2.0.0.22.bin" ]; then file="gimbal/${key}_2.0.0.22.bin"
  else
    # Try glob for gimbal files
    file=$(ls gimbal/"${key}"_*.bin 2>/dev/null | head -1 || true)
  fi
  if [ -z "$file" ] || [ ! -f "$file" ]; then
    echo "  MISSING: $key (expected MD5 $expected_md5)"
    FAIL=1; continue
  fi
  actual_md5=$(md5sum "$file" | cut -d" " -f1)
  if [ "$actual_md5" = "$expected_md5" ]; then
    echo "  OK: $key ($actual_md5)"
  else
    echo "  MISMATCH: $key expected=$expected_md5 actual=$actual_md5"
    FAIL=1
  fi
done < firmwareInfo
if [ $FAIL -eq 0 ]; then
  echo "All MD5s verified. Ready to trigger."
else
  echo "MD5 verification FAILED." >&2
  exit 1
fi
VERIFY_EOF

# --- 4. Trigger --------------------------------------------------------------
if [ "$SKIP_TRIGGER" = "1" ]; then
  echo "--- [4/6] SKIPPED (--skip-trigger) ---"
else
  echo "--- [4/6] Triggering reboot (on-boot watcher will run SP_UpgradeCheckFw) ---"
  # Record uptime so we can prove the device actually booted fresh. An AP-link
  # flap makes SSH disappear for minutes while the box keeps running; treating
  # that as a reboot is how a .67 install was reported as done when it never ran.
  UPTIME_BEFORE="$(ssh -o BatchMode=yes "$SSH" 'awk "{print int(\$1)}" /proc/uptime' 2>/dev/null || echo "")"
  echo "Uptime before reboot: ${UPTIME_BEFORE:-<unknown>}s"
  ssh -o BatchMode=yes "$SSH" 'sync; /sbin/reboot' 2>/dev/null || true
  echo "Reboot sent. Device will be dark for 5-10 min (NAND reflash)."
fi

# --- 5. Wait -----------------------------------------------------------------
if [ "$SKIP_TRIGGER" = "1" ] || [ "$SKIP_VERIFY" = "1" ]; then
  echo "--- [5/6] SKIPPED ---"
else
  echo "--- [5/6] Waiting up to ${MAX_WAIT}s for device to return ---"
  # Phase A: wait for the device to actually go DOWN (reboot in progress).
  # Without this, a fast first probe can succeed before the reboot takes
  # effect and we'd "confirm" against a half-rebooted box.
  echo "  Phase A: waiting for device to go dark..."
  down=0
  while [ $down -lt 60 ]; do
    if ! timeout 5 ssh -o BatchMode=yes -o ConnectTimeout=5 "$SSH" 'true' 2>/dev/null; then
      down=999; break
    fi
    sleep 5
    down=$(( down + 5 ))
  done
  if [ $down -ge 999 ]; then
    echo "  Device is dark (reboot in progress)."
  else
    echo "  WARN: device still up after 60s; reboot may not have taken. Continuing."
  fi
  # Phase B: wait for SSH to return (NAND reflash + boot, 5-10 min).
  elapsed=0
  while [ $elapsed -lt $MAX_WAIT ]; do
    if timeout 5 ssh -o BatchMode=yes -o ConnectTimeout=5 "$SSH" 'true' 2>/dev/null; then
      echo "Device back after ~${elapsed}s."
      break
    fi
    sleep 15
    elapsed=$(( elapsed + 15 ))
    [ $(( elapsed % 60 )) -eq 0 ] && echo "  ...still waiting (${elapsed}s)"
  done
  if [ $elapsed -ge $MAX_WAIT ]; then
    echo "WARN: device not back after ${MAX_WAIT}s. Best-effort verify follows."
  fi
  # Prove the reboot actually happened: a fresh boot resets /proc/uptime, whereas
  # an AP-link flap leaves it climbing. Fail closed rather than confirm against a
  # device that never reflashed.
  if [ -n "$UPTIME_BEFORE" ]; then
    UPTIME_AFTER="$(ssh -o BatchMode=yes -o ConnectTimeout=5 "$SSH" 'awk "{print int(\$1)}" /proc/uptime' 2>/dev/null || echo "")"
    if [ -z "$UPTIME_AFTER" ]; then
      echo "ERROR: cannot read uptime after reboot — cannot prove the flash ran." >&2
      exit 5
    fi
    echo "Uptime after reboot: ${UPTIME_AFTER}s (was ${UPTIME_BEFORE}s)"
    if [ "$UPTIME_AFTER" -ge "$UPTIME_BEFORE" ]; then
      echo "ERROR: uptime did not reset (${UPTIME_BEFORE}s -> ${UPTIME_AFTER}s): the device never rebooted." >&2
      echo "       This is an AP-link flap, not a flash. Nothing was installed." >&2
      exit 5
    fi
    echo "Reboot confirmed by uptime reset."
  else
    echo "WARN: uptime before reboot unknown; cannot prove the flash ran from uptime alone."
  fi
  # Settle for polestar_app to finish init
  sleep 30
fi

# --- 6. Confirm --------------------------------------------------------------
if [ "$SKIP_VERIFY" = "1" ]; then
  echo "--- [6/6] SKIPPED (--skip-verify) ---"
else
  echo "--- [6/6] Confirming install ---"
  if [ -z "$EXPECTED_BUILD_ID" ]; then
    echo "ERROR: candidate build-source-provenance.txt has no build_id" >&2
    exit 4
  fi
  # /app/FwVer does not contain the build_id.  The old script compared the
  # wrong fields and turned a mismatch into a warning, which allowed a test
  # against 15i to be reported as a test of a later candidate.  Compare the
  # immutable build_id, both source commits, and the display version together.
  "$(dirname "$0")/../verify-installed-build.sh" "$BUILD_DIR" \
    --host "$HOST" --ssh-user "$SSH_USER"

  # Check Mlog for the upgrade result
  UPGRADE_LOG="$(ssh -o BatchMode=yes "$SSH" 'grep -aiE "CHECK_FW|UPGRADE|FwVer|SP_UpgradeCheckFw" /app/Mlog.txt 2>/dev/null | tail -10' || true)"
  if [ -n "$UPGRADE_LOG" ]; then
    echo "Recent upgrade log lines:"
    echo "$UPGRADE_LOG" | sed 's/^/  /'
  fi
fi

echo
echo "=== release-fwpkt.sh complete ==="
