"""Execute polaris-httpd and prove the web UI actually opens, and keeps opening.

Two defects made "OpenPolaris does not open" a permanent user experience, and
neither is visible by reading the source. Both were found by running the server
and doing what a browser does.

1. Content-Encoding: gzip was emitted purely from how an asset happened to be
   stored, ignoring the request. A client that did not ask for gzip -- curl
   without --compressed, a proxy, a hardened browser that strips
   Accept-Encoding -- was handed 14 KB of gzip bytes declared to be
   text/html. It decodes to nothing, has no </html>, and looks exactly like a
   truncated download. RFC 9110: Content-Encoding describes the stored
   representation; the payload must be acceptable regardless of Accept-Encoding.

2. handle() ran inline on the single select() thread and called read() with no
   deadline. Browsers routinely open a speculative connection and send nothing
   on it (preconnect, a backgrounded tab, a warm proxy socket). select() reports
   readiness the instant a connection lands, so the server accepted, entered
   handle(), and blocked in read() forever. Every later request -- including
   GET / from the next tab -- queued behind it and timed out, while the port
   stayed open and still answered a bare TCP connect, so the process looked
   healthy from outside. This is the same single-threaded accept loop noted in
   #348; the silent-connection case is what makes it reproducible on demand.

These tests compile and run the real binary rather than grepping it, for the
same reason test_wifi_api_contract.py does: "answered 200" and "answered 200 with
bytes a browser can render" are different claims, and only a live request tells
them apart. Skips are loud -- an unexecuted gate test is the #292/#299 failure
mode this repo has been bitten by twice.
"""
from __future__ import annotations

import gzip
import shutil
import socket
import subprocess
import sys
import time
import urllib.request
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
ASTRO = REPO / "container" / "astro"
EMBED = ASTRO / "embed_webui.py"
WEBUI = ASTRO / "webui"
SOURCES = [
    ASTRO / "polaris-httpd.c",
    ASTRO / "polaris-link.c",
    ASTRO / "polaris-jog.c",
    ASTRO / "polaris-prog.c",
    ASTRO / "polaris-astro.c",
]


def _free_port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


@pytest.fixture(scope="module")
def httpd(tmp_path_factory):
    """Build polaris-httpd for the host and run it on a spare port.

    webui.h is generated by embed_webui.py and gitignored, so it is generated
    here rather than assumed present: a test that relies on a stale webui.h in a
    working tree passes locally and skips silently in the prerelease gate, which
    runs from a fresh clone.
    """
    if shutil.which("gcc") is None:
        pytest.skip("gcc unavailable; serving can only be checked by executing "
                    "the server")
    work = tmp_path_factory.mktemp("httpd")

    embed = subprocess.run(
        [sys.executable, str(EMBED), str(WEBUI), str(work / "webui.h")],
        capture_output=True, text=True,
    )
    if embed.returncode != 0 or not (work / "webui.h").exists():
        pytest.skip("could not generate webui.h, so polaris-httpd cannot be "
                    "built here: "
                    + (embed.stderr or embed.stdout).strip()[-200:])

    binary = work / "polaris-httpd"
    build = subprocess.run(
        ["gcc", "-O0", "-I", str(work), "-o", str(binary)]
        + [str(p) for p in SOURCES] + ["-lm"],
        capture_output=True, text=True,
    )
    if build.returncode != 0:
        pytest.skip("polaris-httpd does not build on this host: "
                    + build.stderr.strip().splitlines()[-1][:200])

    port = _free_port()
    astro = work / "astro"
    astro.mkdir()
    proc = subprocess.Popen(
        [str(binary), "--port", str(port), "--lat", "55.95", "--lon", "-3.19",
         "--astro", str(astro)],
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
    )
    deadline = time.time() + 10
    try:
        while time.time() < deadline:
            try:
                with socket.create_connection(("127.0.0.1", port), timeout=0.3):
                    break
            except OSError:
                if proc.poll() is not None:
                    pytest.skip("polaris-httpd exited on startup on this host")
                time.sleep(0.1)
        else:
            pytest.skip("polaris-httpd never accepted a connection within 10 s")
        yield proc, port
    finally:
        proc.terminate()
        try:
            proc.wait(timeout=5)
        except subprocess.TimeoutExpired:
            proc.kill()


def _raw_get(port: int, accept_encoding: str | None, timeout: float = 8.0):
    """GET / and return (headers_dict, body_bytes) without any auto-decoding."""
    req = urllib.request.Request(f"http://127.0.0.1:{port}/")
    if accept_encoding is not None:
        req.add_header("Accept-Encoding", accept_encoding)
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return {k.lower(): v for k, v in r.headers.items()}, r.read()


def test_plain_client_gets_readable_html(httpd):
    """A client that never mentions gzip must receive real HTML.

    This is the exact failure the user reported. Before the fix the response was
    Content-Encoding: gzip with a 14 KB gzip body, so the page rendered as
    binary garbage with no closing tags and looked like a truncated file.
    """
    _, port = httpd
    headers, body = _raw_get(port, None)

    assert "content-encoding" not in headers, (
        "gzip was sent to a client that did not ask for it; the browser/proxy "
        "will render raw gzip bytes as text")
    assert body[:15].lower().startswith(b"<!doctype html"), (
        f"body is not HTML, starts with {body[:24]!r}")
    assert b"</html>" in body, "HTML is truncated -- no closing </html>"
    assert b"</body>" in body, "HTML is truncated -- no closing </body>"


def test_gzip_client_still_gets_compressed(httpd):
    """Compression is still offered to clients that ask for it.

    Guards the other direction: an over-eager "just stop gzipping" fix would
    regress the 56 KB -> 14 KB transfer, which matters on the head's own AP.
    """
    _, port = httpd
    headers, body = _raw_get(port, "gzip")

    assert headers.get("content-encoding", "").lower() == "gzip", (
        "a client that asked for gzip was not given it")
    assert body[:3] == b"\x1f\x8b\x08", "body is not a gzip stream"
    plain = gzip.decompress(body)
    assert plain[:15].lower().startswith(b"<!doctype html")
    assert b"</html>" in plain


def test_explicit_refusal_of_gzip_is_honoured(httpd):
    """Accept-Encoding: gzip;q=0 is a refusal, not an agreement.

    A substring match on "gzip" would treat this as consent and send bytes the
    client has explicitly declined to decode.
    """
    _, port = httpd
    headers, body = _raw_get(port, "gzip;q=0, deflate")

    assert "content-encoding" not in headers, (
        "q=0 means do not use gzip; the header was ignored")
    assert body[:15].lower().startswith(b"<!doctype html")


def test_vary_header_present(httpd):
    """The response now differs on Accept-Encoding, so caches must be told.

    Without Vary, a shared cache can store the gzipped response and hand it to a
    client that cannot decode it -- reintroducing the original bug for only some
    users, which is far harder to diagnose than an always-broken one.
    """
    _, port = httpd
    headers, _ = _raw_get(port, None)
    assert "accept-encoding" in headers.get("vary", "").lower()


def test_both_encodings_decode_to_the_same_page(httpd):
    """The raw and gzip copies must not drift apart.

    Both forms are embedded now. If the embedder ever emitted a stale or
    mismatched copy, one class of client would silently receive an older UI.
    """
    _, port = httpd
    _, plain = _raw_get(port, None)
    _, comp = _raw_get(port, "gzip")
    assert gzip.decompress(comp) == plain, (
        "the gzipped and identity copies of the page differ")


def test_silent_client_does_not_stop_the_server(httpd):
    """A connection that sends nothing must not wedge the UI for everyone else.

    This is the reproduction of "does not open". Before the fix, one such socket
    blocked handle() in read() indefinitely and every subsequent request timed
    out until that socket was closed -- verified on v110 by holding one silent
    connection and watching four consecutive GETs time out at 8 s each.

    The head-read deadline bounds it, so the worst case is a short delay rather
    than a dead server. The assertion is deliberately generous (the deadline is
    3 s) but far below the old infinite hang.
    """
    _, port = httpd

    silent = socket.create_connection(("127.0.0.1", port), timeout=5)
    try:
        # A browser loading the page issues several requests back to back while
        # that speculative socket sits idle. None may hang.
        for attempt in range(3):
            t0 = time.time()
            _raw_get(port, "gzip", timeout=12.0)
            elapsed = time.time() - t0
            assert elapsed < 8.0, (
                f"request {attempt} took {elapsed:.1f}s behind a silent client; "
                "the accept loop is blocking again")
    finally:
        silent.close()

    # And it must be fully healthy once the socket is gone.
    _raw_get(port, "gzip", timeout=8.0)


def test_assets_serve_to_plain_clients(httpd):
    """CSS and JS are embedded too, so they had the same defect."""
    _, port = httpd
    for path, marker in (("/app.css", b"--bg"), ("/app.js", b"function")):
        req = urllib.request.Request(f"http://127.0.0.1:{port}{path}")
        with urllib.request.urlopen(req, timeout=8) as r:
            raw = r.read()
            hdrs = {k.lower(): v for k, v in r.headers.items()}
        assert "content-encoding" not in hdrs, f"{path} gzipped at a plain client"
        assert marker in raw, f"{path} does not look like itself"
